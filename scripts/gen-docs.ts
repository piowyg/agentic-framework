// Generates docs/reference/{config,commands}.md; `--check` fails when they are stale (CI).
import fs from 'node:fs';
import path from 'node:path';
import type { Command, Option } from 'commander';
import { stringify } from 'yaml';
import { buildProgram } from '../src/cli/program.js';
import { DEFAULTS } from '../src/config/defaults.js';
import { configSchema } from '../src/config/schema.js';
import { PACKAGE_ROOT } from '../src/paths.js';

type Node = {
  type?: string;
  enum?: unknown[];
  anyOf?: Node[];
  description?: string;
  properties?: Record<string, Node>;
  additionalProperties?: Node | boolean;
  patternProperties?: Record<string, Node>;
  items?: Node;
};

const HEADER = '<!-- Generated by `npm run docs`; do not edit by hand. -->\n\n';

function configDoc(): string {
  const rows: string[] = [];
  const walk = (node: Node, keyPath: string, defaults: unknown) => {
    for (const [key, child] of Object.entries(node.properties ?? {})) {
      const childPath = keyPath ? `${keyPath}.${key}` : key;
      const defaultValue = (defaults as Record<string, unknown> | undefined)?.[key];
      const desc = isExecutor(child) ? child.description?.replace(/^Session executor: .*$/, '') || '' : child.description ?? '';
      rows.push(`| \`${childPath}\` | ${typeOf(child)} | ${formatDefault(defaultValue, child)} | ${desc} |`);
      if (child.properties && !isExecutor(child)) walk(child, childPath, defaultValue);
      else if (mapValue(child)?.properties) walk(mapValue(child)!, `${childPath}.<name>`, undefined);
    }
  };
  walk(configSchema as Node, '', DEFAULTS);
  return `${HEADER}# Config reference

The config loads from four layers (a lower one overrides a higher one): global \`~/.agentic/config.yaml\` (+ the active profile)
→ team workspace \`.agentic/config.yaml\` → repo \`.agentic/config.yaml\` → flow. Objects merge recursively,
arrays are replaced whole. To see the result: \`agentic config show\`.

| Field | Type | Default | Description |
|---|---|---|---|
${rows.join('\n')}

## Executor

The \`{ harness, model, effort }\` object used in \`tiers\`, \`stages\`, \`review\`:

| Field | Type | Description |
|---|---|---|
| \`harness\` | \`claude\` \\| \`codex\` | The agent CLI; omitted = inferred from the model catalog. |
| \`model\` | string | Alias from the model catalog (\`agentic models\`). |
| \`effort\` | \`low\` \\| \`medium\` \\| \`high\` \\| \`xhigh\` \\| \`max\` | Effort level; availability depends on the model. |

## Defaults

\`\`\`yaml
${stringify(DEFAULTS).trim()}
\`\`\`
`;
}

/** Value schema of a map: TypeBox `Record` emits `patternProperties`. */
function mapValue(node: Node): Node | undefined {
  if (typeof node.additionalProperties === 'object') return node.additionalProperties;
  return Object.values(node.patternProperties ?? {})[0];
}

function isExecutor(node: Node): boolean {
  return Object.keys(node.properties ?? {}).join() === 'harness,model,effort';
}

function typeOf(node: Node): string {
  if (isExecutor(node)) return '[executor](#executor)';
  if (node.enum) return node.enum.map((value) => `\`${String(value)}\``).join(' \\| ');
  if (node.anyOf) return node.anyOf.map(typeOf).join(' \\| ');
  if (node.type === 'array') return `${node.items ? typeOf(node.items) : 'any'}[]`;
  if (node.type === 'object' && !node.properties && mapValue(node)) return 'map';
  if (node.type === 'object' && node.properties && !node.description && Object.keys(node.properties).length === 1) {
    const [key, value] = Object.entries(node.properties)[0]!;
    return `\`{${key}: ${value.type}}\``;
  }
  return node.type ?? 'any';
}

function formatDefault(defaultValue: unknown, node: Node): string {
  if (defaultValue === undefined || (node.properties && !isExecutor(node))) return '';
  const json = JSON.stringify(defaultValue);
  return json.length > 60 ? '(see below)' : `\`${json.replace(/\|/g, '\\|')}\``;
}

function commandsDoc(): string {
  const program = buildProgram();
  const sections: string[] = [];
  const walk = (command: Command, prefix: string) => {
    for (const subcommand of command.commands) {
      const name = `${prefix} ${subcommand.name()}`;
      if (subcommand.commands.length) {
        walk(subcommand, name);
        continue;
      }
      const args = subcommand.registeredArguments.map((argument) => (argument.required ? `<${argument.name()}>` : `[${argument.name()}]`)).join(' ');
      const lines = [`## \`${name}${args ? ' ' + args : ''}\``, '', subcommand.description()];
      if (subcommand.registeredArguments.length) {
        lines.push('', '| Argument | Description |', '|---|---|');
        for (const argument of subcommand.registeredArguments) lines.push(`| \`${argument.name()}\` | ${argument.description} |`);
      }
      const opts = subcommand.options as Option[];
      if (opts.length) {
        lines.push('', '| Option | Description |', '|---|---|');
        for (const option of opts) {
          const choices = option.argChoices ? ` (${option.argChoices.map((choice) => `\`${choice}\``).join(', ')})` : '';
          lines.push(`| \`${option.flags}\` | ${option.description}${choices} |`);
        }
      }
      sections.push(lines.join('\n'));
    }
  };
  walk(program, 'agentic');
  return `${HEADER}# Commands\n\n${program.description()}\n\n${sections.join('\n\n')}\n`;
}

const outputs: Record<string, string> = {
  'docs/reference/config.md': configDoc(),
  'docs/reference/commands.md': commandsDoc(),
};

const check = process.argv.includes('--check');
let stale = false;
for (const [relativePath, content] of Object.entries(outputs)) {
  const file = path.join(PACKAGE_ROOT, relativePath);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (current === content) continue;
  if (check) {
    console.error(`Stale: ${relativePath}; run \`npm run docs\``);
    stale = true;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`Wrote ${relativePath}`);
  }
}

if (stale) process.exitCode = 1;
